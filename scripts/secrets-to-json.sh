#!/bin/bash

# Проверяем, передан ли файл
if [ -z "$1" ]; then
    echo "Ошибка: Укажите путь к файлу с ключом."
    echo "Использование: $0 <путь_к_файлу_ключа>"
    exit 1
fi

KEY_FILE="$1"

# Проверяем, существует ли файл
if [ ! -f "$KEY_FILE" ]; then
    echo "Ошибка: Файл '$KEY_FILE' не найден."
    exit 1
fi

# Читаем ключ, заменяя реальные переносы строк на символы \n
# awk заменяет каждый перевод строки на \n и собирает в одну строку
ESCAPED_KEY=$(awk '{printf "%s\\n", $0}' "$KEY_FILE")

# Формируем JSON
# Использование одинарных кавычек снаружи защищает структуру внутри
printf '{"host":"","port":"","user":"","key":"%s"}\n' "$ESCAPED_KEY"
